// Validate real 512-KiB slicing with a mocked private Drive blob, no network.
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/../apps-script/Code.gs','utf8');
const root='ROOTFOLDERABCDEFGHIJKLM',doc='DOCUMENTABCDEFGHIJKLMNO';
const audioId='cccccccc-cccc-4ccc-8ccc-cccccccccccc';
const size=700000;
const original=Uint8Array.from({length:size},(_,i)=>i%251);
const audioFile={isTrashed:()=>false,getSize:()=>size,getBlob:()=>({getBytes:()=>Array.from(original)})};
const folder={isTrashed:()=>false,getId:()=>root};
const ctx={Buffer,Utilities:{base64Encode:x=>Buffer.from(x).toString('base64')},DriveApp:{getFileById:()=>audioFile,getFolderById:()=>folder}};
vm.createContext(ctx);vm.runInContext(source,ctx);
ctx.bvlDoc_=()=>({getSheetByName:()=>({})});
ctx.bvlAudioEntry_=()=>[audioId,'TARGET','log',audioId+'.webm','audio/webm','FILEIDABCDEFGHIJKL','FOLDERIDABCDEFGHIJKL'];
ctx.bvlParentIs_=()=>true;
const p={doc_id:doc,audio_id:audioId,offset:0};
const a=ctx.bvlAudioRead_(root,'TEMPLATETEST123456',p);
assert.strictEqual(a.ok,true);
assert.strictEqual(a.next,524288);
assert.strictEqual(a.size,size);
const b=ctx.bvlAudioRead_(root,'TEMPLATETEST123456',{...p,offset:a.next});
assert.strictEqual(b.next,size);
const joined=Buffer.concat([Buffer.from(a.base64,'base64'),Buffer.from(b.base64,'base64')]);
assert.ok(joined.equals(Buffer.from(original)),'The two decoded segments must match all original bytes');
assert.ok(a.base64.length<1024*1024,'Single chunk must fit WP 1MiB bridge body limit');
console.log('PASS v0.6.1: audio chunk responses preserve all 700,000 bytes across 2 requests.');
